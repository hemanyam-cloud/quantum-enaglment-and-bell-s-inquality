/**
 * Quantum Circuit Simulator and OpenQASM 2.0 / 3.0 Exporter for CHSH experiments.
 */
import { Complex, c } from '../core/complex.js';
import { GATES } from '../core/observables.js';
import { Matrix } from '../core/matrix.js';

export class QuantumCircuitSimulator {
  /**
   * Generates OpenQASM 2.0 representation of CHSH circuit.
   */
  static toOpenQASM2({
    stateType = 'phiPlus',
    thetaA = 0,
    phiA = 0,
    thetaB = Math.PI / 4,
    phiB = 0
  } = {}) {
    let qasm = `// CHSH Entanglement Experiment generated by QuantumBellPlatform\n`;
    qasm += `OPENQASM 2.0;\ninclude "qelib1.inc";\n\nqreg q[2];\ncreg c[2];\n\n`;

    // State preparation
    qasm += `// State preparation: ${stateType}\n`;
    if (stateType === 'phiPlus') {
      qasm += `h q[0];\ncx q[0], q[1];\n`;
    } else if (stateType === 'phiMinus') {
      qasm += `x q[0];\nh q[0];\ncx q[0], q[1];\n`;
    } else if (stateType === 'psiPlus') {
      qasm += `x q[1];\nh q[0];\ncx q[0], q[1];\n`;
    } else if (stateType === 'psiMinus') {
      qasm += `x q[0];\nx q[1];\nh q[0];\ncx q[0], q[1];\n`;
    }

    qasm += `\n// Basis rotation for Alice (theta=${thetaA.toFixed(4)}, phi=${phiA.toFixed(4)})\n`;
    if (Math.abs(phiA) > 1e-6) qasm += `rz(${-phiA.toFixed(4)}) q[0];\n`;
    if (Math.abs(thetaA) > 1e-6) qasm += `ry(${-thetaA.toFixed(4)}) q[0];\n`;

    qasm += `\n// Basis rotation for Bob (theta=${thetaB.toFixed(4)}, phi=${phiB.toFixed(4)})\n`;
    if (Math.abs(phiB) > 1e-6) qasm += `rz(${-phiB.toFixed(4)}) q[1];\n`;
    if (Math.abs(thetaB) > 1e-6) qasm += `ry(${-thetaB.toFixed(4)}) q[1];\n`;

    qasm += `\n// Measurement in computational Z basis\nmeasure q[0] -> c[0];\nmeasure q[1] -> c[1];\n`;
    return qasm;
  }

  /**
   * Generates OpenQASM 3.0 representation.
   */
  static toOpenQASM3({
    stateType = 'phiPlus',
    thetaA = 0,
    phiA = 0,
    thetaB = Math.PI / 4,
    phiB = 0
  } = {}) {
    let qasm = `// CHSH Bell Test OpenQASM 3.0\nOPENQASM 3.0;\ninclude "stdgates.inc";\n\n`;
    qasm += `qubit[2] q;\nbit[2] c;\n\n`;

    if (stateType === 'phiPlus') {
      qasm += `h q[0];\ncx q[0], q[1];\n`;
    }

    if (Math.abs(phiA) > 1e-6) qasm += `rz(${-phiA.toFixed(4)}) q[0];\n`;
    if (Math.abs(thetaA) > 1e-6) qasm += `ry(${-thetaA.toFixed(4)}) q[0];\n`;

    if (Math.abs(phiB) > 1e-6) qasm += `rz(${-phiB.toFixed(4)}) q[1];\n`;
    if (Math.abs(thetaB) > 1e-6) qasm += `ry(${-thetaB.toFixed(4)}) q[1];\n`;

    qasm += `c = measure q;\n`;
    return qasm;
  }
}
